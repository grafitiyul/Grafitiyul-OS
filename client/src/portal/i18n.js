// THE Guide Portal translation registry.
//
// One file, two languages, every static UI string in the portal. Nothing in
// the portal may write a user-visible literal inline, and no screen may carry
// its own `lang === 'en' ? … : …` ternary — that is exactly how a product ends
// up half-translated. Screens call `t.<group>.<key>` and nothing else.
//
// SCOPE — this file covers CHROME only:
//   * buttons, titles, labels, empty states, errors, badges, navigation,
//     status words, confirmations, section headings, aria labels
// It deliberately contains ZERO business data. Product names, city names,
// customer names, ticket types, guide notes, payroll component names and
// training content are DATA: they are resolved from their own bilingual
// columns on the server (shared/bilingualText.mjs) or shipped verbatim. Adding
// a business value to this file would be a translation-in-code bug.
//
// The language itself is decided ONCE, on the server, from the canonical staff
// language field — see server/src/tours/guidePortal/access.js. This file never
// reads navigator.language.

export const PORTAL_LANGUAGES = ['he', 'en'];
export const DEFAULT_PORTAL_LANGUAGE = 'he';

/** Text direction for a portal language. Hebrew is the only RTL language. */
export function portalDir(lang) {
  return lang === 'en' ? 'ltr' : 'rtl';
}

export function isPortalRtl(lang) {
  return portalDir(lang) === 'rtl';
}

/** Normalize anything the server/router hands us to a supported language. */
export function normalizePortalLanguage(value) {
  const v = String(value ?? '').trim().toLowerCase();
  return PORTAL_LANGUAGES.includes(v) ? v : DEFAULT_PORTAL_LANGUAGE;
}

